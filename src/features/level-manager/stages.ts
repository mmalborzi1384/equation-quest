export const stageOrder = stages.map(({ id }) => id);
if (stageOrder.length !== levels.length || stageOrder.some((id, i) => id !== levels[i].id))
  throw new Error('stage content must match the eight authored route IDs');
export function stageFor(id: string) {
  return stages.find((stage) => stage.id === id);
}
